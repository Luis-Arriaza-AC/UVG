/* USER CODE BEGIN 4 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART1)
  {
    // Acumular caracteres hasta recibir salto de línea ('\n' o '\r')
    if (rx_byte != '\r' && rx_byte != '\n')
    {
      if (rx_index < sizeof(rx_line) - 1)
      {
        rx_line[rx_index++] = (char)rx_byte;
      }
    }
    else if (rx_index > 0)
    {
      rx_line[rx_index] = '\0'; // Finalizar la cadena recibida

      // Comparaciones simples para actualizar los registros
      if (strcmp(rx_line, "up1") == 0)         arriba = 1;
      else if (strcmp(rx_line, "up0") == 0)    arriba = 0;
      else if (strcmp(rx_line, "down1") == 0)  abajo = 1;
      else if (strcmp(rx_line, "down0") == 0)  abajo = 0;
      else if (strcmp(rx_line, "left1") == 0)  izquierda = 1;
      else if (strcmp(rx_line, "left0") == 0)  izquierda = 0;
      else if (strcmp(rx_line, "right1") == 0) derecha = 1;
      else if (strcmp(rx_line, "right0") == 0) derecha = 0;
      else if (strcmp(rx_line, "A1") == 0)     botonA = 1;
      else if (strcmp(rx_line, "A0") == 0)     botonA = 0;
      else if (strcmp(rx_line, "B1") == 0)     botonB = 1;
      else if (strcmp(rx_line, "B0") == 0)     botonB = 0;

      rx_index = 0; // Reiniciar buffer
    }

    // Re-habilitar la interrupción para el siguiente carácter
    HAL_UART_Receive_IT(&huart1, &rx_byte, 1);
  }
}

void Process_Nano_Buttons(void)
{
  char tx_buf[128] = "C2: [ ";
  uint8_t hay_presionado = 0;

  if (arriba)    { strcat(tx_buf, "Arriba ");    hay_presionado = 1; }
  if (abajo)     { strcat(tx_buf, "Abajo ");     hay_presionado = 1; }
  if (izquierda) { strcat(tx_buf, "Izquierda "); hay_presionado = 1; }
  if (derecha)   { strcat(tx_buf, "Derecha ");   hay_presionado = 1; }
  if (botonA)    { strcat(tx_buf, "A ");         hay_presionado = 1; }
  if (botonB)    { strcat(tx_buf, "B ");         hay_presionado = 1; }

  // Solo transmite a la PC si hay al menos un botón presionado
  if (hay_presionado)
  {
    strcat(tx_buf, "]\r\n");
    HAL_UART_Transmit(&huart2, (uint8_t*)tx_buf, strlen(tx_buf), HAL_MAX_DELAY);
  }
}

// --- Procesamiento ADC Joystick ---
void Process_Joystick(void)
{
  if (adc_buffer[0] > 2800)       joy_y_state = "C1: Arriba\r\n";
  else if (adc_buffer[0] < 1200)  joy_y_state = "C1: Abajo\r\n";
  else                            joy_y_state = "";

  if (adc_buffer[1] > 2800)       joy_x_state = "C1: Derecha\r\n";
  else if (adc_buffer[1] < 1200)  joy_x_state = "C1: Izquierda\r\n";
  else                            joy_x_state = "";

  if (joy_y_state != prev_joy_y && strlen(joy_y_state) > 0) {
    HAL_UART_Transmit(&huart2, (uint8_t*)joy_y_state, strlen(joy_y_state), HAL_MAX_DELAY);
    prev_joy_y = joy_y_state;
  }

  if (joy_x_state != prev_joy_x && strlen(joy_x_state) > 0) {
    HAL_UART_Transmit(&huart2, (uint8_t*)joy_x_state, strlen(joy_x_state), HAL_MAX_DELAY);
    prev_joy_x = joy_x_state;
  }
}


