static uint16_t stageLevel;
void Stage_SetLevel(uint16_t level) { stageLevel = level; }
uint16_t Stage_Pixel(int x, int y) {
    if (x < 0 || x >= STAGE_WIDTH || y < 0 || y >= STAGE_HEIGHT) return 0;
    if ((x < 32 || x >= STAGE_WIDTH - 32) && y >= 48 && y < 96) {
        if (y < 50) return 0;
        y -= 2;
    }
    uint8_t cell = map[y / 8][x / 8];
    unsigned id = cell & 0x7FU;
    if (id == 0U) return 0;
    unsigned sx = (unsigned)x & 7U;
    if (cell & 0x80U) sx = 7U - sx;
    if (id == 1U) {
        if (stageLevel == 2U) id = 2U;
        else if (stageLevel >= 3U) id = 13U;
    }
    return stageTiles[id - 1U][((unsigned)y & 7U)*8U + sx];
}

//Solo ladrillos y plataformas: las tuberias son decorativas.
uint8_t Stage_IsSolid(int x, int y) {
    if (x < 0 || x >= STAGE_WIDTH || y < 0 || y >= STAGE_HEIGHT) return 0;
    uint8_t id = map[y / 8][x / 8] & 0x7FU;
    return id == 1U || id == 14U;
}

//tuberías decorativas
uint8_t Stage_IsPipe(int x, int y) {
    if (x < 0 || x >= STAGE_WIDTH || y < 0 || y >= STAGE_HEIGHT) return 0;
    uint8_t id = map[y / 8][x / 8] & 0x7FU;
    return (id >= 3U && id <= 10U) || (id >= 15U && id <= 22U);
}


uint8_t Stage_GetPlatformSpan(int x, int y, int *left, int *right, int *top) {
    if (x < 0 || x >= STAGE_WIDTH || y < 0 || y >= STAGE_HEIGHT) return 0;
    int tx = x / 8;
    int ty = y / 8;
    uint8_t id = map[ty][tx] & 0x7FU;
    if (id != 1U && id != 14U) return 0;
    int l = tx, r = tx;
    while (l > 0) {
        uint8_t n = map[ty][l - 1] & 0x7FU;
        if (n != 1U && n != 14U) break;
        --l;
    }
    while (r + 1 < 30) {
        uint8_t n = map[ty][r + 1] & 0x7FU;
        if (n != 1U && n != 14U) break;
        ++r;
    }
    if (left) *left = l * 8;
    if (right) *right = (r + 1) * 8;
    if (top) *top = ty * 8;
    return 1;
}
