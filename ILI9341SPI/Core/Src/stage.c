uint16_t Stage_Pixel(int x, int y) {
    if (x < 0 || x >= STAGE_WIDTH || y < 0 || y >= STAGE_HEIGHT) return 0;
    uint8_t cell = map[y / 8][x / 8];
    unsigned id = cell & 0x7FU;
    if (id == 0U) return 0;
    unsigned sx = (unsigned)x & 7U;
    if (cell & 0x80U) sx = 7U - sx;
    return tiles[id - 1U][((unsigned)y & 7U)*8U + sx];
}
